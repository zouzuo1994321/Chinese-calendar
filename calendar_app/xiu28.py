def xiu_figure(name):
    """取某宿的线稿：``(stars, edges)``；未知宿返回 ``None``。"""
    return XIU_STARS.get(name)


def xiu_full_name(name, zheng="", animal=""):
    """「柳土獐」式的完整宿名。

    已知宿名一律取本模块 `XIU_CHIN`（通行通书口径，见文件头说明）；
    未知宿名退回「宿 + 七曜 + 禽」；七曜/禽都缺时退化为「柳宿」。
    """
    t = XIU_CHIN.get(name)
    if t:
        return "%s%s%s" % (name, t[0], t[1])
    if zheng and animal:
        return "%s%s%s" % (name, zheng, animal)
    if zheng:
        return "%s%s" % (name, zheng)
    return "%s宿" % name


