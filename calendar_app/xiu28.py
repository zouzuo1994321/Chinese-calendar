# 依古刻本形态手工定稿；星数取「可辨识」为准，繁宿主星较多的作精简。


def _ring(cx, cy, rx, ry, a0, a1, n):
    """生成一段椭圆弧上的 n 个点（角度：0° 指向 +x，逆时针为正）。"""
    import math
    pts = []
    for i in range(n):
        a = math.radians(a0 + (a1 - a0) * i / float(n - 1))
        pts.append((round(cx + rx * math.cos(a), 4),
                    round(cy - ry * math.sin(a), 4)))
    return pts


def _chain(n):
    return [(i, i + 1) for i in range(n - 1)]


