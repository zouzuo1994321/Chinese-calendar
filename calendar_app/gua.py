def _num_of(n: int) -> int:
    """÷8 取余映射到先天八卦数 1..8（余 0 作 8 = 坤）。"""
    r = n % 8
    return r if r else 8


def daily_gua(info: dict):
    """按「梅花易数年月日式」推出当日卦象（日粒度固定）。

    :return: {"name","full","upper","lower","lines","desc","basis"} 或 None（数据缺失）
      - ``name``  卦名（如「泰」）
      - ``full``  全名（如「地天泰」；八纯卦作「乾为天」）
      - ``upper`` / ``lower`` 外卦 / 内卦，形如「坤(地)」
      - ``lines`` 六爻，**自下而上**（第 1 爻在前），1 = 阳、0 = 阴
      - ``desc``  一句话简释
      - ``basis`` 起卦依据（如「年支3＋月7＋日23（＋日支9）」）
    """
    gz = (info or {}).get("day_ganzhi") or ""
    ygz = (info or {}).get("year_ganzhi") or ""
    lm = (info or {}).get("lunar_month_num")
    ld = (info or {}).get("lunar_day_num")
    if (len(gz) < 2 or len(ygz) < 2 or not lm or not ld
            or gz[1] not in ZHI_ORDER or ygz[1] not in ZHI_ORDER):
        return None
    yb = ZHI_ORDER.index(ygz[1]) + 1          # 年支数 子 1 … 亥 12
    zb = ZHI_ORDER.index(gz[1]) + 1           # 日支数 子 1 … 亥 12
    base = yb + int(lm) + int(ld)             # 上卦用数
    up_n = _num_of(base)                      # 上卦（外卦）
    lo_n = _num_of(base + zb)                 # 下卦（内卦）
    up_name, up_nat, up_lines = XIAN_TIAN[up_n]
    lo_name, lo_nat, lo_lines = XIAN_TIAN[lo_n]
    r, c = _TRIGRAM_SEQ.index(up_name), _TRIGRAM_SEQ.index(lo_name)
    name = GUA64[r][c]
    full = ("%s为%s" % (name, up_nat)) if up_name == lo_name \
        else ("%s%s%s" % (up_nat, lo_nat, name))
    return {
        "name": name,
        "full": full,
        "upper": "%s(%s)" % (up_name, up_nat),
        "lower": "%s(%s)" % (lo_name, lo_nat),
        "lines": tuple(lo_lines) + tuple(up_lines),   # 内卦 1..3 爻 + 外卦 4..6 爻
        "desc": GUA_DESC.get(name, ""),
        "basis": "年支%d＋月%d＋日%d（＋日支%d）" % (yb, int(lm), int(ld), zb),
    }


def gua_tip(gua: dict) -> str:
    """悬停提示文案（卦名 / 内外卦 / 简释 / 起卦依据）。

    v1.9.21：用户反馈「悬停窗中 行与行间隔太大，改到紧凑些」——原先在「上下卦」之后与
    「简释」之后各插了一个空行（`\\n\\n`），QToolTip 的空行同样是整行行高，
    四段因此实占 6 行、区块间距达到约两倍行距。改为**全部单换行**（4 行紧排），
    区块间距回到约 1 行，提示窗高度减少约 33%（13px 黑体实测 114px → 76px）。
    ⚠ 不要再插空行分段 —— 需要视觉分区时用行内分隔符（如「·」）而不是空行。
    """
    if not gua:
        return ""
    return "%s卦（%s）\n上%s　下%s\n%s\n起卦　%s　· 梅花易数年月日式" % (
        gua["name"], gua["full"], gua["upper"], gua["lower"],
        gua["desc"], gua.get("basis", ""))
